from __future__ import annotations

import inspect
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("OPENSWX_CACHE", "off")
os.environ.setdefault("OPENSWX_AUTOSAVE", "off")
os.environ.setdefault("OPENSWX_LOG", "off")
os.environ["OPENSWX_PLUGINS"] = "off"  # (the reference lists the built-in commands, whatever is installed here)

ORDER = ["document", "query", "edit", "view", "sketch", "features", "bodies", "surfaces", "sheet_metal", "weldments",
         "mold", "configurations", "equations", "library", "assembly", "routing", "drawing", "mbd", "inspection",
         "evaluate", "simulation", "cam", "plastics", "render", "composer", "pdm", "file", "tools"]
TITLES = {"sheet_metal": "Sheet metal", "mbd": "MBD (DimXpert)", "pdm": "PDM", "cam": "CAM", "query": "Queries",
          "edit": "Edit and history", "document": "Documents and files", "file": "Publishing", "tools": "Macros",
          "routing": "Electrical routing", "evaluate": "Evaluate", "render": "Rendering"}


def _signature(fn) -> str:
    parts = []
    for p in inspect.signature(fn).parameters.values():
        ann = p.annotation if isinstance(p.annotation, str) else getattr(p.annotation, "__name__", str(p.annotation))
        ann = re.sub(r"\btyping\.", "", str(ann))
        s = f"{p.name}: {ann}"
        if p.default is not inspect.Parameter.empty:
            s += f" = {p.default!r}"
        parts.append(s)
    return ", ".join(parts)


def commands_md() -> str:
    from openswx import session as S
    by: dict[str, list[str]] = {}
    for name, meta in S.COMMANDS.items():
        by.setdefault(meta["category"], []).append(name)
    cats = [c for c in ORDER if c in by] + sorted(c for c in by if c not in ORDER)
    n, n_mcp = len(S.COMMANDS), sum(1 for m in S.COMMANDS.values() if m["mcp"])
    out = ["# openswx commands", "",
           "Generated by `tools/gen_command_docs.py` from the command registry; do not edit by hand.", "",
           f"{n} commands. {n_mcp} of them are MCP tools; the others (marked *UI only*) are used by the web UI. "
           "Every command is also `POST /api/command {\"name\": ..., \"args\": {...}}` and a function in "
           "`openswx.session`. Lengths are millimetres, angles degrees.", "",
           "| Area | Commands |", "|---|---|"]
    for c in cats:
        title = TITLES.get(c, c.capitalize())
        out.append(f"| [{title}](#{re.sub(r'[^a-z0-9 -]', '', title.lower()).replace(' ', '-')}) | {len(by[c])} |")
    for c in cats:
        out += ["", f"## {TITLES.get(c, c.capitalize())}", ""]
        for name in by[c]:
            meta = S.COMMANDS[name]
            flags = [] if meta["mcp"] else ["UI only"]
            if not meta["mutates"]:
                flags.append("read-only")
            out.append(f"### `{name}`" + (f" *({', '.join(flags)})*" if flags else ""))
            out += ["", "```", f"{name}({_signature(meta['fn'])})", "```", ""]
            doc = " ".join((meta["doc"] or "").split())
            out.append(doc or "(no description)")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def readme_counts(text: str) -> str:
    """README.md with the block between the `<!-- counts -->` markers rewritten."""
    from openswx import session as S
    n, n_mcp = len(S.COMMANDS), sum(1 for m in S.COMMANDS.values() if m["mcp"])
    block = (f"<!-- counts -->{n} commands, {n_mcp} of them MCP tools "
             f"([full list](https://github.com/DukeOfCheese/openswx/blob/main/docs/commands.md))<!-- /counts -->")
    new, k = re.subn(r"<!-- counts -->.*?<!-- /counts -->", block, text, flags=re.S)
    return new if k else text


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, new in ((ROOT / "docs" / "commands.md", commands_md()),
                      (ROOT / "README.md", readme_counts((ROOT / "README.md").read_text(encoding="utf-8")))):
        old = path.read_text(encoding="utf-8") if path.exists() else ""
        if old.replace("\r\n", "\n") != new.replace("\r\n", "\n"):
            stale.append(path.name)
            if not check:
                path.write_text(new, encoding="utf-8", newline="\n")
    if check and stale:
        print("out of date: " + ", ".join(stale) + "  (run python tools/gen_command_docs.py)")
        return 1
    print("up to date" if not stale else "rewrote " + ", ".join(stale))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
